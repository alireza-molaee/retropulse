import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { createApp } from '../server.js';

test('two participants complete a retro and retrieve it after restart', async () => {
  const folder = await mkdtemp(join(tmpdir(), 'retro-'));
  let server;
  async function start() {
    server = createApp(join(folder, 'board.sqlite'));
    server.listen(0, '127.0.0.1');
    await once(server, 'listening');
    return 'http://127.0.0.1:' + server.address().port;
  }
  let base;
  async function call(path, status, secret, body) {
    const headers = secret ? { Authorization: 'Bearer ' + secret } : {};
    const response = await fetch(base + '/api/boards' + path, {
      method: body ? 'POST' : 'GET', body: body && JSON.stringify(body), headers,
    });
    const data = await response.json();
    assert.equal(response.status, status, JSON.stringify(data));
    return data;
  }
  try {
    base = await start();
    for (const path of ['/', '/app.js', '/style.css']) {
      const asset = await fetch(base + path);
      assert.equal(asset.status, 200);
      assert.ok((await asset.text()).length);
    }
    const defaultBoard = await call('', 201, null, { title: 'Default', name: 'Host' });
    assert.equal(defaultBoard.board.voteLimit, 3);
    assert.equal(defaultBoard.board.survey, null);
    await call('', 400, null, { title: 'Invalid', name: 'Host', voteLimit: 0 });
    await call('', 400, null, { title: 'Invalid', name: 'Host', voteLimit: 1.5 });
    await call('', 400, null, { title: 'Invalid', name: 'Host', avatar: 49 });
    const survey = [{ text: 'How was the sprint?', options: ['Good', 'Hard'] }, { text: 'What next?', options: ['Testing', 'Planning'] }];
    await call('', 400, null, { title: 'Invalid survey', name: 'Host', survey: [{ ...survey[0], options: ['Same', 'Same'] }] });
    const host = await call('', 201, null, { title: 'Retro', name: 'Host', voteLimit: 2, avatar: 1, survey });
    assert.equal(host.board.me.avatar, 1);
    const path = '/' + host.id;
    const guest = await call(path + '/join', 201, null, { name: 'Guest', avatar: 48 });
    assert.equal(guest.board.voteLimit, 2);
    await call(path, 401);
    const mutation = (member, type, data, status = 200) => call(path + '/change', status, member.secret, { type, ...data });
    assert.deepEqual(guest.board.survey.questions, survey);
    await mutation(guest, 'survey-response', { answers: [0] }, 400);
    await mutation(guest, 'survey-response', { answers: [0, 2] }, 400);
    await mutation(guest, 'survey-response', { answers: [1, 1] });
    await mutation(guest, 'survey-response', { answers: [0, 1] });
    assert.deepEqual((await call(path, 200, host.secret)).survey, { questions: survey, answers: null, results: null });
    await mutation(host, 'survey-response', { answers: [0, 0] });
    await mutation(guest, 'phase', {}, 403);
    await mutation(guest, 'start-timer', { seconds: 5 }, 403);
    await mutation(host, 'start-timer', { seconds: 0 }, 400);
    const started = await mutation(host, 'start-timer', { seconds: 8 });
    assert.ok(started.timer.endsAt > started.serverNow);
    assert.deepEqual((await call(path, 200, guest.secret)).timer, started.timer);
    await mutation(guest, 'reset-timer', {}, 403);
    assert.deepEqual((await mutation(host, 'reset-timer')).timer, { seconds: 8, endsAt: null });
    const readiness = { phase: 'write', ready: true };
    await mutation(guest, 'ready', readiness);
    await mutation(guest, 'ready', readiness);
    assert.deepEqual((await call(path, 200, host.secret)).roster.map(member => member.ready), [false, true]);
    await mutation(guest, 'ready', { ...readiness, ready: false });
    await mutation(host, 'ready', readiness);
    await mutation(guest, 'reset-ready', { phase: 'write' }, 403);
    assert.ok((await mutation(host, 'reset-ready', { phase: 'write' })).roster.every(member => !member.ready));
    await mutation(guest, 'ready', readiness);
    await mutation(host, 'phase', { direction: 'previous' }, 403);
    const written = await mutation(guest, 'note', { column: 'good', text: 'Pairing' });
    const note = written.notes[0].id;
    assert.equal((await call(path, 200, host.secret)).notes.length, 0);
    await mutation(host, 'delete', { note }, 403);
    await mutation(guest, 'edit', { note, text: 'More pairing', anonymous: false });
    const second = (await mutation(host, 'note', { column: 'good', text: 'Review together', anonymous: true })).notes[0].id;
    const third = (await mutation(host, 'note', { column: 'good', text: 'Share feedback' })).notes.at(-1).id;
    const visible = await mutation(host, 'phase');
    await mutation(host, 'phase', { fromPhase: 'write' }, 409);
    assert.ok(visible.roster.every(member => !member.ready));
    await mutation(guest, 'ready', readiness, 409);
    assert.equal(visible.notes[0].text, 'More pairing');
    assert.deepEqual(visible.notes[0].attribution, { name: 'Guest', avatar: 48 });
    const guestView = await call(path, 200, guest.secret);
    const privateCard = guestView.notes.find(card => card.id === second);
    assert.equal(privateCard.attribution, null);
    assert.equal(Object.hasOwn(privateCard, 'author'), false);
    assert.deepEqual(guestView.notes.find(card => card.id === third).attribution, { name: 'Host', avatar: 1 });
    await mutation(guest, 'group', { note, target: second }, 403);
    const grouped = await mutation(host, 'group', { note, target: second });
    const anonymousComment = await mutation(guest, 'comment', { note, text: 'Anonymous feedback', anonymous: true });
    const anonymous = anonymousComment.notes.find(card => card.id === note).comments[0];
    assert.equal(anonymous.attribution, null);
    assert.equal(Object.hasOwn(anonymous, 'author'), false);
    const reaction = { note, emoji: '👍', active: true };
    await mutation(guest, 'reaction', reaction);
    await mutation(guest, 'reaction', reaction);
    const hostCard = (await call(path, 200, host.secret)).notes.find(card => card.id === note);
    assert.deepEqual(hostCard.reactions, [{ emoji: '👍', count: 1, active: false }]);
    const target = grouped.groups[0].id;
    assert.equal(grouped.groups[0].title, undefined);
    assert.equal(grouped.notes.filter(card => card.group === target).length, 2);
    assert.equal((await mutation(host, 'group', { note: third, target })).notes.filter(card => card.group === target).length, 3);
    await mutation(host, 'group', { note: third, target: null });
    const dissolved = await mutation(host, 'group', { note: second, target: null });
    assert.equal(dissolved.groups.length, 0);
    const regrouped = await mutation(host, 'group', { note, target: second });
    const voteTarget = regrouped.groups[0].id;
    await mutation(host, 'phase');
    await mutation(guest, 'reaction', { ...reaction, active: false });
    await mutation(guest, 'comment', { note, text: 'Named feedback' });
    for (let i = 0; i < 2; i++) await mutation(guest, 'vote', { target: voteTarget });
    await mutation(guest, 'vote', { target: voteTarget }, 400);
    await mutation(guest, 'unvote', { target: voteTarget });
    await mutation(guest, 'vote', { target: voteTarget });
    assert.deepEqual((await call(path, 200, host.secret)).totals, {});
    const results = await mutation(host, 'phase');
    assert.equal(results.totals[voteTarget], 2);
    await mutation(host, 'reaction', reaction);
    const action = { text: 'Schedule pairing', ownerId: guest.board.me.id, due: '2026-12-01' };
    await mutation(guest, 'action', action, 403);
    await mutation(host, 'action', { ...action, due: '2026-02-30' }, 400);
    await mutation(host, 'action', { ...action, ownerId: 'not-a-member' }, 400);
    await mutation(host, 'action', action);
    await mutation(host, 'phase');
    await mutation(host, 'action', action, 403);
    await mutation(host, 'comment', { note, text: 'After completion' }, 403);
    await mutation(host, 'survey-response', { answers: [1, 1] }, 403);
    await new Promise(resolve => server.close(resolve));
    base = await start();
    const archived = await call(path, 200, guest.secret);
    assert.equal(archived.phase, 'done');
    assert.deepEqual(archived.survey, { questions: survey, answers: [0, 1], results: { respondents: 2, counts: [[2, 0], [1, 1]] } });
    assert.equal(archived.voteLimit, 2);
    assert.equal(archived.me.avatar, 48);
    assert.deepEqual(archived.roster.map(member => member.avatar), [1, 48]);
    assert.equal(archived.totals[voteTarget], 2);
    assert.deepEqual(archived.notes.find(card => card.id === note).attribution, { name: 'Guest', avatar: 48 });
    const archivedCard = archived.notes.find(card => card.id === note);
    assert.deepEqual(archivedCard.comments.map(comment => comment.attribution), [null, { name: 'Guest', avatar: 48 }]);
    assert.deepEqual(archivedCard.reactions, [{ emoji: '👍', count: 1, active: false }]);
    assert.equal(archived.notes.find(card => card.id === second).attribution, null);
    assert.equal(archived.actions[0].owner, 'Guest');
    assert.equal(archived.actions[0].ownerId, action.ownerId);
    await mutation(guest, 'phase', { direction: 'previous' }, 403);
    const reopened = await mutation(host, 'phase', { direction: 'previous' });
    assert.equal(reopened.phase, 'actions');
    assert.equal(reopened.actions[0].ownerId, action.ownerId);
    const voting = await mutation(host, 'phase', { direction: 'previous' });
    assert.equal(voting.phase, 'vote');
    assert.deepEqual((await call(path, 200, guest.secret)).me.votes, [voteTarget, voteTarget]);
    await mutation(host, 'phase', { direction: 'previous' });
    await mutation(host, 'group', { note: second, target: null });
    await mutation(host, 'phase');
    assert.deepEqual((await call(path, 200, guest.secret)).me.votes, []);
  } finally {
    if (server?.listening) await new Promise(resolve => server.close(resolve));
    await rm(folder, { recursive: true, force: true });
  }
});
